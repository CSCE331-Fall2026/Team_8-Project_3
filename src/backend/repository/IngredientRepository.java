package repository;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Types;
import java.util.ArrayList;
import java.util.List;

import models.Ingredient;

import javax.sql.DataSource;

public class IngredientRepository {
    private static final String COLUMNS = "ingredient_id, ingredient_name, quantity_in_stock, "
            + "storage_type::text AS storage_type, ingredient_cost, "
            + "expiry_date::text AS expiry_date, min_qty_on_hand, measurement_units, shelf_life_days";

    private final DataSource pool;

    public IngredientRepository(DataSource pool) {
        this.pool = pool;
    }

    // ingredient_id is generated by the database, so any id in the request is ignored
    public Ingredient createIngredient(Ingredient ingredient) throws SQLException {
        try (Connection conn = pool.getConnection()) {
            PreparedStatement stmt = conn.prepareStatement(
                    "INSERT INTO ingredients (ingredient_name, quantity_in_stock, storage_type, ingredient_cost, "
                            + "expiry_date, min_qty_on_hand, measurement_units, shelf_life_days) "
                            + "VALUES (?, ?, ?::storage_type, ?, ?::timestamptz, ?, ?, ?) "
                            + "RETURNING " + COLUMNS);
            stmt.setString(1, ingredient.ingredientName());
            stmt.setObject(2, ingredient.quantityInStock(), Types.DOUBLE);
            stmt.setString(3, ingredient.storageType() == null ? null : ingredient.storageType().name());
            stmt.setObject(4, ingredient.ingredientCost(), Types.DOUBLE);
            stmt.setString(5, ingredient.expiryDate());
            stmt.setObject(6, ingredient.minQtyOnHand(), Types.DOUBLE);
            stmt.setString(7, ingredient.measurementUnits());
            stmt.setObject(8, ingredient.shelfLifeDays(), Types.INTEGER);
            return query(stmt).get(0);
        }
    }

    public Ingredient getIngredientById(int id) throws SQLException {
        try (Connection conn = pool.getConnection()) {
            PreparedStatement stmt = conn.prepareStatement(
                    "SELECT " + COLUMNS + " FROM ingredients WHERE ingredient_id = ?");
            stmt.setInt(1, id);
            List<Ingredient> ingredients = query(stmt);
            return ingredients.isEmpty() ? null : ingredients.get(0);
        }
    }

    public List<Ingredient> getAllIngredients() throws SQLException {
        try (Connection conn = pool.getConnection()) {
            PreparedStatement stmt = conn.prepareStatement(
                    "SELECT " + COLUMNS + " FROM ingredients ORDER BY ingredient_id");
            return query(stmt);
        }
    }

    // Fields left null in the request keep their current value
    public boolean updateIngredient(int id, Ingredient ingredient) throws SQLException {
        try (Connection conn = pool.getConnection()) {
            PreparedStatement stmt = conn.prepareStatement(
                    "UPDATE ingredients SET ingredient_name = COALESCE(?, ingredient_name), "
                            + "quantity_in_stock = COALESCE(?, quantity_in_stock), "
                            + "storage_type = COALESCE(?::storage_type, storage_type), "
                            + "ingredient_cost = COALESCE(?, ingredient_cost), "
                            + "expiry_date = COALESCE(?::timestamptz, expiry_date), "
                            + "min_qty_on_hand = COALESCE(?, min_qty_on_hand), "
                            + "measurement_units = COALESCE(?, measurement_units), "
                            + "shelf_life_days = COALESCE(?, shelf_life_days) "
                            + "WHERE ingredient_id = ?");
            stmt.setString(1, ingredient.ingredientName());
            stmt.setObject(2, ingredient.quantityInStock(), Types.DOUBLE);
            stmt.setString(3, ingredient.storageType() == null ? null : ingredient.storageType().name());
            stmt.setObject(4, ingredient.ingredientCost(), Types.DOUBLE);
            stmt.setString(5, ingredient.expiryDate());
            stmt.setObject(6, ingredient.minQtyOnHand(), Types.DOUBLE);
            stmt.setString(7, ingredient.measurementUnits());
            stmt.setObject(8, ingredient.shelfLifeDays(), Types.INTEGER);
            stmt.setInt(9, id);
            return stmt.executeUpdate() > 0;
        }
    }

    // Throws an SQLException with state 23503 if a menu item still uses this ingredient
    public boolean deleteIngredient(int id) throws SQLException {
        try (Connection conn = pool.getConnection()) {
            PreparedStatement stmt = conn.prepareStatement("DELETE FROM ingredients WHERE ingredient_id = ?");
            stmt.setInt(1, id);
            return stmt.executeUpdate() > 0;
        }
    }

    private List<Ingredient> query(PreparedStatement stmt) throws SQLException {
        List<Ingredient> ingredients = new ArrayList<>();
        ResultSet rs = stmt.executeQuery();
        while (rs.next()) {
            String storageType = rs.getString("storage_type");
            ingredients.add(new Ingredient(
                    rs.getInt("ingredient_id"),
                    rs.getString("ingredient_name"),
                    rs.getObject("quantity_in_stock", Double.class),
                    storageType == null ? null : Ingredient.StorageType.valueOf(storageType),
                    rs.getObject("ingredient_cost", Double.class),
                    rs.getString("expiry_date"),
                    rs.getObject("min_qty_on_hand", Double.class),
                    rs.getString("measurement_units"),
                    rs.getObject("shelf_life_days", Integer.class)));
        }
        stmt.close();
        return ingredients;
    }
}
